#!/usr/bin/env node
/**
 * Generates a Font Awesome subset containing only the icons this site actually
 * uses, replacing the full CDN build (16 KB of CSS with ~98% unused rules, plus
 * 225 KB of webfonts covering ~2000 glyphs we don't reference).
 *
 * Outputs two committed artifacts:
 *   src/styles/icons.css          — @font-face + only the glyph rules we need
 *   src/assets/fonts/*.woff2      — the subsetted webfonts
 *
 * Both are checked in deliberately. The deploy workflow runs `npm ci && npm run
 * build` on a Node-only runner, and subsetting needs Python's fonttools — so
 * this script is run by hand when the icon list changes, not during the build.
 *
 * Usage:
 *   pip install fonttools brotli      # once
 *   node scripts/build-icon-subset.mjs
 *
 * To add an icon: add its name below, re-run, and commit the regenerated files.
 * Names must match Font Awesome's canonical icon names (the `fa-` prefix is
 * added automatically). The script fails loudly on an unknown name or on one
 * that isn't in the Free tier for the requested style.
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fa = resolve(root, 'node_modules/@fortawesome/fontawesome-free');

/** Icons referenced from markup or injected by client scripts. */
const ICONS = {
  solid: [
    'arrow-down-long',
    'arrow-left',
    'arrow-up-right-from-square',
    'bars',
    'bullhorn',
    'chevron-right',
    'circle-info',
    'circle-question',
    'clipboard-list',
    'envelope',
    'link',
    'list-check',
    'location-dot',
    'magnifying-glass',
    'pause',
    'play', // swapped in by HomeHero's slideshow toggle
    'rotate-left',
    'sliders',
    'xmark', // swapped in by Header's nav toggle
  ],
  brands: [
    'bluesky',
    'facebook',
    'instagram',
    'linkedin',
    'linkedin-in',
    'medium',
    'reddit',
    'slack',
    'tiktok',
    'x-twitter',
  ],
};

const FAMILIES = {
  solid: { family: 'Font Awesome 7 Free', weight: 900, src: 'fa-solid-900' },
  brands: { family: 'Font Awesome 7 Brands', weight: 400, src: 'fa-brands-400' },
};

const metadata = JSON.parse(
  readFileSync(resolve(fa, 'metadata/icon-families.json'), 'utf-8')
);

/** Resolve each icon name to its codepoint, failing loudly on typos. */
function resolveIcons(style, names) {
  return names.map((name) => {
    const icon = metadata[name];
    if (!icon) throw new Error(`Unknown Font Awesome icon: "${name}"`);
    const free = icon.familyStylesByLicense?.free ?? [];
    const ok = free.some((s) => s.family === 'classic' && s.style === style);
    if (!ok) {
      throw new Error(
        `Icon "${name}" is not available as free/${style} ` +
          `(free styles: ${free.map((s) => s.style).join(', ') || 'none'})`
      );
    }
    return { name, unicode: icon.unicode };
  });
}

const resolved = Object.fromEntries(
  Object.entries(ICONS).map(([style, names]) => [style, resolveIcons(style, names)])
);

// ---- subset the webfonts -------------------------------------------------
const fontDir = resolve(root, 'src/assets/fonts');
mkdirSync(fontDir, { recursive: true });

for (const [style, icons] of Object.entries(resolved)) {
  const { src } = FAMILIES[style];
  const unicodes = icons.map((i) => `U+${i.unicode}`).join(',');
  const out = resolve(fontDir, `${src}-subset.woff2`);
  execFileSync('pyftsubset', [
    resolve(fa, `webfonts/${src}.woff2`),
    `--unicodes=${unicodes}`,
    '--flavor=woff2',
    '--layout-features=',
    '--no-hinting',
    '--desubroutinize',
    `--output-file=${out}`,
  ]);
  console.log(`${src}-subset.woff2  ${icons.length} glyphs`);
}

// ---- generate the stylesheet --------------------------------------------
const faceFor = (style) => {
  const { family, weight, src } = FAMILIES[style];
  return `@font-face {
  font-family: "${family}";
  font-style: normal;
  font-weight: ${weight};
  /* swap, not block: Font Awesome ships font-display: block, which held text
     invisible for ~220 ms in the Lighthouse run. */
  font-display: swap;
  src: url("../assets/fonts/${src}-subset.woff2") format("woff2");
}`;
};

const glyphsFor = (style) =>
  resolved[style]
    .map((i) => `.fa-${i.name}::before { content: "\\${i.unicode}"; }`)
    .join('\n');

const css = `/* GENERATED by scripts/build-icon-subset.mjs — do not edit by hand.
   Add icons to that script's ICONS list and re-run it instead.

   Contains only the ${resolved.solid.length + resolved.brands.length} icons this site uses. Replaces the full Font
   Awesome CDN build, which was render-blocking from a third-party origin. */

${faceFor('solid')}

${faceFor('brands')}

.fa,
.fa-solid,
.fa-brands,
.fas,
.fab {
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
  display: var(--fa-display, inline-block);
  font-family: var(--fa-family, "Font Awesome 7 Free");
  font-style: normal;
  font-synthesis: none;
  font-variant: normal;
  font-weight: var(--fa-style, 900);
  line-height: 1;
  text-align: center;
  text-rendering: auto;
  width: var(--fa-width, 1.25em);
}

.fa-solid,
.fas {
  --fa-family: "Font Awesome 7 Free";
  --fa-style: 900;
}

.fa-brands,
.fab {
  --fa-family: "Font Awesome 7 Brands";
  --fa-style: 400;
}

/* solid */
${glyphsFor('solid')}

/* brands */
${glyphsFor('brands')}
`;

writeFileSync(resolve(root, 'src/styles/icons.css'), css);
console.log(`icons.css        ${resolved.solid.length + resolved.brands.length} glyph rules`);
